/** Returns the {@link CountryCapital} for the given alpha-2 code, or `null` if unknown. */
export function getCountryCapital(alpha2: string): CountryCapital | null {
  const r = RAW[alpha2];
  if (!r) return null;
  return new CountryCapital(r.en, r.sv, r.native, GeoCoordinate.create(r.lat, r.lon));
}
